def main():
    gid = {g[0]: g for g in GROUPS}
    out, seen = [], set()
    for n, (g, p, tag, src) in enumerate(I, 1):
        assert g in gid, g
        assert p not in seen, '중복 ' + p
        seen.add(p)
        out.append(dict(id=f'b{n:03d}', g=g, lv=gid[g][2], p=p, tag=tag, src=src))
